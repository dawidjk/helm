import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';
import {fileURLToPath} from 'node:url';

// Prose remains authoritative in its existing TypeScript sources. Only the
// small catalog and the requested article payload need to reach the browser.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cache = new Map();
function load(name) {
  const file = path.resolve(root, 'src/pages', `${name}.ts`);
  if (cache.has(file)) return cache.get(file);
  const exports = {};
  cache.set(file, exports);
  const source = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: {module: ts.ModuleKind.CommonJS},
  }).outputText;
  vm.runInNewContext(source, {exports, require: (name) => load(path.basename(name))}, {filename: file});
  return exports;
}
const {articles} = load('articles');
const {articleSupport} = load('articleSupport');
const directory = path.join(root, 'public/article-data');
fs.mkdirSync(directory, {recursive: true});
for (const file of fs.readdirSync(directory)) if (file.endsWith('.json')) fs.unlinkSync(path.join(directory, file));
const catalog = articles.map(({slug, title, lane, readMin}) => ({slug, title, lane, readMin}));
if (new Set(catalog.map((article) => article.slug)).size !== articles.length) throw new Error('Duplicate article slug');
for (const article of articles) {
  const support = articleSupport[article.slug];
  if (!support) throw new Error(`Missing article support: ${article.slug}`);
  fs.writeFileSync(path.join(directory, `${article.slug}.json`), JSON.stringify({article, support}));
}
fs.writeFileSync(path.join(root, 'src/pages/articleCatalog.ts'),
  '// Generated by scripts/generate-article-data.mjs. Edit the authoritative article sources.\n' +
  'export const articleCatalog = ' + JSON.stringify(catalog, null, 2) + ';\n');
console.log(`Prepared ${articles.length} individual article payloads and a metadata-only catalog.`);
